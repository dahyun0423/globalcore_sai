/**
 * AI로 보내기 전에 인터뷰 메모에서 식별정보를 가린다.
 * 완벽하지 않으므로 이름·학교명은 애초에 메모에 쓰지 않는 게 원칙.
 */
export function maskPII(text: string): string {
  return text
    .replace(/[\w.+-]+@[\w-]+\.[\w.-]+/g, "[이메일]")
    .replace(/(\+?\d{1,3}[-\s]?)?0?\d{1,2}[-\s]?\d{3,4}[-\s]?\d{4}/g, "[전화번호]")
    .replace(/\d{6}[-\s]?[1-4]\d{6}/g, "[주민번호]")
    .replace(/[가-힣]{1,3}(초등학교|국민소학|國小)/g, "[학교]")
    .replace(/[가-힣]{2,4}(엄마|아빠|어머니|아버지|선생님|쌤)/g, "[보호자·교사]");
}
